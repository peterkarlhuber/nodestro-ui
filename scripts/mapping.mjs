// The mapping from each product's current custom properties to the --ui- tokens.
// Source of truth: migration/<product>.json. This script renders docs/token-mapping.md from it.
//
//   node scripts/mapping.mjs --write            render docs/token-mapping.md
//   node scripts/mapping.mjs --check            fail if docs/token-mapping.md is not current
//   node scripts/mapping.mjs --verify <dir>     compare the inventory with the product checkouts under <dir>
//                                               (<dir>/<repository name>/<file>); names and values must match
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT, readJson } from "./lib/workspaces.mjs";
import { inventory } from "./lib/inventory.mjs";

export const MIGRATION_DIR = join(ROOT, "migration");
export const DOC = join(ROOT, "docs", "token-mapping.md");

export function loadMappings() {
  return readdirSync(MIGRATION_DIR)
    .filter((f) => f.endsWith(".json"))
    .sort()
    .map((f) => readJson(join(MIGRATION_DIR, f)));
}

export function loadTokens() {
  return readJson(join(ROOT, "packages", "tokens", "src", "tokens.json"));
}

const cell = (text) => String(text ?? "").replaceAll("|", "\\|");
const code = (text) => (text ? `\`${cell(text)}\`` : "");

function productValue(v) {
  return "value" in v ? code(v.value) : `${code(v.light)} / ${code(v.dark)}`;
}

function tokenValue(token) {
  return "value" in token ? code(token.value) : `${code(token.values.light)} / ${code(token.values.dark)}`;
}

export function renderDoc(mappings = loadMappings(), source = loadTokens()) {
  const ui = (name) => `--${source.prefix}-${name}`;
  const lines = [
    "# Token mapping",
    "",
    "<!-- Generated by `npm run mapping` from migration/*.json: do not edit. -->",
    "",
    "How each product's current custom properties map to the brand-neutral `--ui-` tokens. The products are not",
    "migrated yet; this is the plan for that step (see docs/TODO.md). A mapping is by role: the token has the same",
    "meaning, and the product keeps its own values in its brand theme. Variables without a token stay in the",
    "product. Values are as declared in the product file at the commit named below (light / dark for themed",
    "variables).",
    "",
    "| Product | File | Last changed in | Variables | Mapped | Stay in product |",
    "|---|---|---|---|---|---|",
  ];
  for (const m of mappings) {
    const mapped = m.variables.filter((v) => v.token).length;
    lines.push(
      `| ${m.product} | \`${m.source.file}\` | \`${m.source.commit.slice(0, 12)}\` | ${m.variables.length} | ${mapped} | ${m.variables.length - mapped} |`,
    );
  }
  for (const m of mappings) {
    lines.push("", `## ${m.product} (\`${m.source.prefix}\`)`, "");
    for (const note of m.notes) lines.push(`- ${note}`);
    lines.push("", "| Product variable | Product value | Token | Default value | Note |", "|---|---|---|---|---|");
    for (const v of m.variables) {
      const token = v.token ? source.tokens[v.token] : null;
      lines.push(
        `| \`${v.name}\` | ${productValue(v)} | ${v.token ? code(ui(v.token)) : "stays"} | ${token ? tokenValue(token) : ""} | ${cell(v.note)} |`,
      );
    }
  }
  lines.push("", "## By token", "", "Which product variables each token replaces. Tokens without a source are new.", "");
  lines.push("| Token | Replaces |", "|---|---|");
  for (const name of Object.keys(source.tokens)) {
    const from = mappings.flatMap((m) => m.variables.filter((v) => v.token === name).map((v) => code(v.name)));
    lines.push(`| ${code(ui(name))} | ${from.join(", ") || "new"} |`);
  }
  return `${lines.join("\n")}\n`;
}

/** Differences between the recorded inventory and a product checkout. */
export function verify(mapping, css) {
  const live = inventory(css, mapping.source.selectors, mapping.source.prefix);
  const problems = [];
  const recorded = new Map(mapping.variables.map((v) => [v.name, v]));
  for (const [name, values] of live) {
    const v = recorded.get(name);
    if (!v) problems.push(`${name}: in the product, not in the mapping`);
    else {
      for (const key of ["value", "light", "dark"]) {
        if (values[key] !== v[key]) problems.push(`${name}: ${key} is ${values[key]} in the product, ${v[key]} in the mapping`);
      }
    }
  }
  for (const name of recorded.keys()) if (!live.has(name)) problems.push(`${name}: in the mapping, not in the product`);
  return problems;
}

if (process.argv[1]?.endsWith("mapping.mjs")) {
  const args = process.argv.slice(2);
  if (args.includes("--write")) {
    writeFileSync(DOC, renderDoc());
    console.log(`wrote ${DOC}`);
  } else if (args.includes("--check")) {
    if (readFileSync(DOC, "utf-8") !== renderDoc()) {
      console.error("docs/token-mapping.md is not current: run npm run mapping");
      process.exit(1);
    }
    console.log("docs/token-mapping.md is current");
  } else if (args.includes("--verify")) {
    const dir = args[args.indexOf("--verify") + 1];
    if (!dir) throw new Error("--verify needs the directory that holds the product checkouts");
    let failed = false;
    for (const m of loadMappings()) {
      const repo = m.source.repository.split("/")[1];
      const problems = verify(m, readFileSync(join(dir, repo, m.source.file), "utf-8"));
      for (const p of problems) console.error(`${m.product}: ${p}`);
      if (problems.length) failed = true;
      else console.log(`${m.product}: ${m.variables.length} variables match`);
    }
    if (failed) process.exit(1);
  } else {
    console.error("usage: node scripts/mapping.mjs --write | --check | --verify <dir>");
    process.exit(2);
  }
}
